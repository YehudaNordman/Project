import React, { useState, useEffect } from 'react';

/**
 * רכיב המציג את כל המסלולים שהמשתמש שמר ב-localStorage.
 * כולל אפשרות להורדת המסלול כקובץ PDF בצורה מעוצבת ותומכת RTL.
 */
const SavedItinerariesView = ({ onBack }) => {
    const [savedTrips, setSavedTrips] = useState([]);
    const [expandedTrip, setExpandedTrip] = useState(null);

    useEffect(() => {
        const data = JSON.parse(localStorage.getItem('saved_itineraries') || '[]');
        setSavedTrips(data);
    }, []);

    const deleteTrip = (e, timestamp) => {
        e.stopPropagation();
        const updated = savedTrips.filter(t => t.timestamp !== timestamp);
        localStorage.setItem('saved_itineraries', JSON.stringify(updated));
        setSavedTrips(updated);
        if (expandedTrip === timestamp) setExpandedTrip(null);
    };

    const toggleExpand = (timestamp) => {
        setExpandedTrip(expandedTrip === timestamp ? null : timestamp);
    };

    /**
     * פונקציה להורדת מסלול ספציפי כ-PDF - תיקון סופי למניעת דריסת טקסט (עברית ואנגלית)
     */
    const downloadDestinationPDF = (e, trip) => {
        e.stopPropagation();
        const element = document.createElement('div');

        // פונקציית עזר לעטיפת טקסט לטיני/מספרי כדי למנוע היפוך ודריסה
        const wrapLtr = (html) => {
            if (!html) return "";
            // מחפש מחרוזות אנגליות/מספריות ארוכות מ-2 תווים ועוטף אותן ב-span עם dir="ltr"
            return html.replace(/([a-zA-Z0-9][a-zA-Z0-9\s:/-]{1,}[a-zA-Z0-9])/g, (match) => {
                if (match.startsWith('<') || match.endsWith('>')) return match;
                return `<span dir="ltr" style="display: inline-block; unicode-bidi: isolate; white-space: nowrap;">${match}</span>`;
            });
        };

        const cleanAiPlan = wrapLtr(trip.aiPlan)
            .replace(/<h3>(.*?)<\/h3>/g, (m, g) => `<h3 style="color: #1a237e; border-right: 4px solid #86BDBF; padding-right: 15px; margin-top: 25px; text-align: right; text-rendering: optimizeLegibility;">${g}</h3>`)
            .replace(/<li>(.*?)<\/li>/g, (m, g) => `<li style="margin-bottom: 12px; text-align: right; display: flex; flex-direction: row-reverse; justify-content: flex-end; gap: 10px;">${g}</li>`);

        const pdfStyles = `<style>
            .pdf-body { direction: rtl; unicode-bidi: isolate; text-align: right; font-family: 'Arial', sans-serif; padding: 30px; background: white; color: #333; text-rendering: optimizeLegibility; }
            .pdf-table { width: 100%; border-collapse: collapse; }
            .pdf-header-cell { border-bottom: 3px solid #86BDBF; padding-bottom: 20px; }
            .trip-row-flex { display: flex; flex-direction: row-reverse; justify-content: space-between; align-items: center; margin-top: 15px; background: #f8f9fa; padding: 10px 15px; border-radius: 8px; }
            .timestamp-badge { white-space: nowrap; font-weight: bold; color: #1a237e; direction: ltr; display: inline-block; background: #e8eaf6; padding: 4px 12px; border-radius: 15px; font-size: 14px; }
        </style>`;

        element.innerHTML = `${pdfStyles}
            <div class="pdf-body">
                <table class="pdf-table">
                    <tr><td class="pdf-header-cell">
                        <div style="float: left; font-size: 26px; font-weight: 900; color: #1a237e;">Bonus<span style="color: #86BDBF;">Trip</span></div>
                        <div style="float: right;"><h1 style="margin: 0; color: #008080; font-size: 32px;">${trip.destination} 🌍</h1></div>
                        <div style="clear: both;"></div>
                    </td></tr>
                    <tr><td style="padding-top: 20px;">
                        <div class="trip-row-flex">
                            <div style="font-size: 18px; font-weight: bold; color: #1a237e;">תכנית הטיול שלך</div>
                            <div class="timestamp-badge">
                                <span dir="ltr">${trip.landingDate} (${trip.landingTime})</span> ➜ <span dir="ltr">${trip.takeoffDate} (${trip.takeoffTime})</span>
                            </div>
                        </div>
                    </td></tr>
                    <tr><td style="padding-top: 30px;"><div style="font-size: 15px; line-height: 1.8;">${cleanAiPlan}</div></td></tr>
                </table>
                <div style="margin-top: 60px; text-align: center; font-size: 11px; color: #999; border-top: 1px solid #eee; padding-top: 20px;">
                    Generated by <strong>BonusTrip</strong> | www.bonustrip.co.il
                </div>
            </div>`;

        window.html2pdf().from(element).set({
            margin: [0.4, 0.4],
            filename: `BonusTrip_${trip.destination}.pdf`,
            html2canvas: { scale: 2, useCORS: true, letterRendering: true },
            jsPDF: { unit: 'in', format: 'a4', orientation: 'portrait' }
        }).save();
    };

    return (
        <div className="explorer-page animate-in" dir="rtl">
            <div className="explorer-header glass">
                <button className="back-btn-simple" onClick={onBack}>חזור</button>
                <div className="header-text-group">
                    <h2>המסלולים השמורים שלי 💾</h2>
                    <p>צפייה בכל הטיולים שתכננת בעזרת ה-AI</p>
                </div>
            </div>

            <div className="explorer-content" style={{ flexDirection: 'column', gap: '1.2rem', paddingBottom: '4rem', alignItems: 'center' }}>
                {savedTrips.length > 0 ? (
                    savedTrips.map((trip, index) => {
                        const isExpanded = expandedTrip === trip.timestamp;
                        return (
                            <div
                                key={trip.timestamp || index}
                                className={`saved-trip-card glass animate-in ${isExpanded ? 'active-expanded' : ''}`}
                                onClick={() => toggleExpand(trip.timestamp)}
                                style={{
                                    width: '100%',
                                    maxWidth: '650px',
                                    cursor: 'pointer',
                                    background: isExpanded ? 'rgba(255, 255, 255, 1)' : 'rgba(255, 255, 255, 0.15)',
                                    borderRadius: '25px',
                                    border: '1px solid rgba(0, 128, 128, 0.2)',
                                    padding: '25px',
                                    boxShadow: isExpanded ? '0 20px 50px rgba(0,0,0,0.1)' : '0 10px 30px rgba(0,0,0,0.05)',
                                    textAlign: 'right'
                                }}
                            >
                                <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start' }}>
                                    <div style={{ flex: 1 }}>
                                        <div style={{ display: 'flex', alignItems: 'center', gap: '12px', marginBottom: '8px' }}>
                                            <h3 style={{
                                                margin: 0,
                                                fontSize: '2.8rem',
                                                color: '#008080',
                                                fontFamily: "'Inter', sans-serif",
                                                fontWeight: '900',
                                                lineHeight: '1.1'
                                            }}>
                                                {trip.destination}
                                            </h3>
                                            <span style={{ fontSize: '2.8rem' }}>🌍</span>
                                        </div>

                                        <div style={{
                                            fontSize: '1.2rem',
                                            color: '#333',
                                            fontWeight: '500',
                                            opacity: 0.9,
                                            display: 'flex',
                                            alignItems: 'center',
                                            gap: '8px'
                                        }}>
                                            <span dir="ltr">({trip.landingTime}) {trip.landingDate}</span>
                                            <span style={{ color: '#008080', fontWeight: '900' }}>➜</span>
                                            <span dir="ltr">({trip.takeoffTime}) {trip.takeoffDate}</span>
                                        </div>
                                    </div>

                                    <button
                                        onClick={(e) => deleteTrip(e, trip.timestamp)}
                                        className="delete-trip-btn-circle"
                                        style={{
                                            background: 'rgba(255, 0, 0, 0.08)',
                                            color: '#ff4444',
                                            border: 'none',
                                            width: '32px',
                                            height: '32px',
                                            borderRadius: '50%',
                                            cursor: 'pointer'
                                        }}
                                    >✕</button>
                                </div>

                                {isExpanded && (
                                    <div className="trip-full-plan animate-in" style={{
                                        marginTop: '25px',
                                        paddingTop: '25px',
                                        borderTop: '1px dashed rgba(0, 128, 128, 0.3)'
                                    }}>
                                        <div className="ai-content-wrapper" style={{ maxHeight: '500px', overflowY: 'auto', paddingRight: '10px' }}>
                                            <div className="ai-content" dangerouslySetInnerHTML={{ __html: trip.aiPlan }} />
                                        </div>

                                        <div style={{ marginTop: '25px', display: 'flex', justifyContent: 'center' }}>
                                            <button
                                                className="pdf-download-btn"
                                                onClick={(e) => downloadDestinationPDF(e, trip)}
                                            >
                                                <svg viewBox="0 0 24 24" width="18" height="18" stroke="currentColor" strokeWidth="2.5" fill="none" style={{ marginLeft: '10px' }}>
                                                    <path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"></path>
                                                    <polyline points="7 10 12 15 17 10"></polyline>
                                                    <line x1="12" y1="15" x2="12" y2="3"></line>
                                                </svg>
                                                Download Trip Summary (PDF)
                                            </button>
                                        </div>
                                    </div>
                                )}

                                {!isExpanded && (
                                    <div style={{
                                        marginTop: '15px',
                                        fontSize: '0.85rem',
                                        color: '#008080',
                                        fontWeight: '700',
                                        opacity: 0.6,
                                        textAlign: 'center'
                                    }}>
                                        ↡ לחץ לצפייה במסלול המלא ↡
                                    </div>
                                )}
                            </div>
                        );
                    })
                ) : (
                    <div className="no-results-msg glass" style={{ padding: '3rem' }}>
                        <p style={{ fontSize: '1.5rem', marginBottom: '1.5rem' }}>עדיין לא שמרת אף מסלול... 🏂</p>
                        <button className="retry-btn" onClick={onBack}>התחל לתכנן עכשיו</button>
                    </div>
                )}
            </div>
        </div>
    );
};

export default SavedItinerariesView;
